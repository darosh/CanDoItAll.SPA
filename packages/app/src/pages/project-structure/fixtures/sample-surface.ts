// Hand-written fixture surface covering the node families/shapes and link kinds the ported
// CanvasWorkbench engine renders, for local dev verification via `vp run dev` without needing
// the .NET backend running. Keep this in the repo as a permanent regression fixture — see
// packages/app/src/pages/ProjectStructurePage.vue and the port plan's phase 1-3 checkpoints.

function node(
  partial: Partial<CanvasWorkbenchNode> & Pick<CanvasWorkbenchNode, "id" | "title" | "x" | "y">,
): CanvasWorkbenchNode {
  return {
    id: partial.id,
    parentId: partial.parentId ?? null,
    family: partial.family ?? "item",
    kind: partial.kind ?? "item",
    icon: partial.icon ?? "",
    title: partial.title,
    subtitle: partial.subtitle ?? "",
    leadText: partial.leadText ?? "",
    compactPath: partial.compactPath ?? null,
    status: partial.status ?? "",
    branchLabel: partial.branchLabel ?? "",
    accentColor: partial.accentColor ?? "#7c3aed",
    paletteKey: partial.paletteKey ?? "neutral",
    durationLabel: partial.durationLabel ?? "",
    statusPill: partial.statusPill ?? "",
    progressMode: partial.progressMode ?? "na",
    progressPercent: partial.progressPercent ?? 0,
    markerIcon: partial.markerIcon ?? "",
    markerTone: partial.markerTone ?? "",
    markerLabel: partial.markerLabel ?? "",
    markers: partial.markers ?? [],
    priority: partial.priority ?? 0,
    isRequired: partial.isRequired ?? false,
    isCollapsible: partial.isCollapsible ?? false,
    isReadOnly: partial.isReadOnly ?? false,
    isPreviewOnly: partial.isPreviewOnly ?? false,
    isInlineTextNode: partial.isInlineTextNode ?? false,
    inlineText: partial.inlineText ?? "",
    inlineTextPlaceholder: partial.inlineTextPlaceholder ?? "Write note",
    mediaKind: partial.mediaKind ?? "",
    mediaPreviewUrl: partial.mediaPreviewUrl ?? "",
    mediaPreviewAlt: partial.mediaPreviewAlt ?? "",
    mediaContentType: partial.mediaContentType ?? "",
    mediaFileName: partial.mediaFileName ?? "",
    x: partial.x,
    y: partial.y,
    chips: partial.chips ?? [],
    footerChips: partial.footerChips ?? [],
    annotations: partial.annotations ?? [],
    contextActions: partial.contextActions ?? [],
    inputPorts: partial.inputPorts ?? [],
    outputPorts: partial.outputPorts ?? [],
  };
}

function action(
  partial: Partial<CanvasWorkbenchAction> & Pick<CanvasWorkbenchAction, "actionId" | "label">,
): CanvasWorkbenchAction {
  return {
    actionId: partial.actionId,
    label: partial.label,
    description: partial.description ?? "",
    icon: partial.icon ?? "",
    menuLabel: partial.menuLabel ?? partial.label,
    shortcutKey: partial.shortcutKey ?? "",
    menuSize: partial.menuSize ?? "normal",
    submenuLayout: partial.submenuLayout ?? "",
    tone: partial.tone ?? "neutral",
    setupRendererKey: partial.setupRendererKey ?? "",
    requiresInput: partial.requiresInput ?? false,
    createMode: partial.createMode ?? "command",
    objectSubtype: partial.objectSubtype ?? "",
    titleLabel: partial.titleLabel ?? "Title",
    titlePlaceholder: partial.titlePlaceholder ?? "",
    subtitleLabel: partial.subtitleLabel ?? "Subtitle",
    subtitlePlaceholder: partial.subtitlePlaceholder ?? "",
    notesLabel: partial.notesLabel ?? "Notes",
    notesPlaceholder: partial.notesPlaceholder ?? "",
    showDefaultTextFields: partial.showDefaultTextFields ?? true,
    submitLabel: partial.submitLabel ?? "Create",
    requiresFile: partial.requiresFile ?? false,
    acceptedFileTypes: partial.acceptedFileTypes ?? "",
    filePrompt: partial.filePrompt ?? "",
    supportsDragDrop: partial.supportsDragDrop ?? true,
    inputFields: partial.inputFields ?? [],
    defaultInputValues: partial.defaultInputValues ?? [],
    children: partial.children ?? [],
  };
}

